#!/usr/bin/env python3
"""Turn a binary file into a C array definition.

Run by zephyr/CMakeLists.txt at configure time, so it needs no build-system
custom command (PlatformIO's Zephyr builder does not execute those).
"""
import argparse
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--input", type=Path, help="omit for an empty array")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    data = args.input.read_bytes() if args.input else b""
    lines = [
        "/* Generated by scripts/embed_blob.py from %s. Do not edit. */"
        % (args.input.name if args.input else "nothing"),
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "const uint8_t %s[] = {" % args.symbol,
    ]
    for offset in range(0, len(data), 16):
        lines.append("\t" + " ".join("0x%02x," % byte for byte in data[offset:offset + 16]))
    if not data:
        lines.append("\t0x00,")
    lines += ["};", "const size_t %s_size = %dU;" % (args.symbol, len(data)), ""]
    text = "\n".join(lines)

    # Leave an unchanged file alone so nothing is recompiled.
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
